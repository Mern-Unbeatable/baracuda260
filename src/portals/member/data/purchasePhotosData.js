export const computePurchaseStats = (items) => {
  const spent = items.reduce((sum, item) => sum + (item.priceValue || 0), 0);
  return {
    total: items.length,
    spent: `$${spent.toFixed(2)}`,
    downloads: items.filter((item) => item.downloadAvailable).length,
  };
};

